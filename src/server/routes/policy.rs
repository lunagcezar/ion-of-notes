//! One declarative policy table for every v2 route.
//!
//! The table is the single source of truth for the capability, block-limit
//! kind, owner-only flag and page-scoped flag. The handler dispatch remains a
//! match in `v2.rs`; this module only owns cross-cutting route metadata.

use super::super::{Capability, Method};

/// How a route pattern is matched against the request path.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum MatchKind {
    Exact,
    Prefix,
}

/// How a write affects the workspace block count.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum BlockLimit {
    None,
    PageCreate,
    DatabaseCreate,
    PageReplace,
    BlockChildren,
}

/// Cross-cutting policy for one v2 method/path shape.
#[derive(Debug, Clone, Copy)]
pub struct RoutePolicy {
    pub methods: &'static [Method],
    pub path: &'static str,
    pub kind: MatchKind,
    /// Optional suffix for a prefix route (for example `/children`).
    pub suffix: Option<&'static str>,
    pub capability: Capability,
    pub block_limit: BlockLimit,
    pub owner_only: bool,
    pub page_scoped: bool,
}

impl RoutePolicy {
    fn matches(&self, method: Method, path: &str) -> bool {
        self.methods.contains(&method)
            && match self.kind {
                MatchKind::Exact => path == self.path,
                MatchKind::Prefix => {
                    path.starts_with(self.path)
                        && self.suffix.is_none_or(|suffix| path.ends_with(suffix))
                }
            }
    }
}

