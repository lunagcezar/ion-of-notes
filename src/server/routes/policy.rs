/// The policy for one method/path, if the route is known.
pub fn route_policy(method: Method, path: &str) -> Option<&'static RoutePolicy> {
    ROUTES.iter().find(|route| route.matches(method, path))
}

/// The capability required by one v2 method/path.
pub fn route_capability(method: Method, path: &str) -> Option<Capability> {
    route_policy(method, path).map(|policy| policy.capability)
}
