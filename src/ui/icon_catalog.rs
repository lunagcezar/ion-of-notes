//! Searchable glyph catalogs for the page-icon picker (SRP).
//!
//! The emoji table pairs each glyph with an English name and extra keywords so
//! the filter can match words instead of raw characters. The icon table only
//! exposes the monochrome shapes already bundled in `ui::icons`; no external
//! icon pack is used (spec-057).

