/// Draw one bundled monochrome icon by name. Used by `draw_page_icon` so a
/// `shape:` page icon reproduces the picker artwork everywhere.
pub fn draw_shape(painter: &egui::Painter, rect: Rect, name: &str, color: Color32) {
    if let Some(entry) = ICONS.iter().find(|entry| entry.name == name) {
        (entry.draw)(painter, rect, color);
    } else {
        painter.text(
            rect.center(),
            egui::Align2::CENTER_CENTER,
            "?",
            egui::FontId::proportional(rect.height() * 0.7),
            color,
        );
    }
}
